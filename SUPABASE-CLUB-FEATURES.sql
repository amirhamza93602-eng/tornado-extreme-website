-- TORNADO EXTREME: Dashboard, announcements, intra-club wins, squad management, verification
-- Run in Supabase SQL Editor as project owner. Overall Stats are intentionally NOT touched.

CREATE TABLE IF NOT EXISTS public.club_announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 3 AND 140),
  body TEXT NOT NULL CHECK (char_length(body) BETWEEN 3 AND 3000),
  created_by UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.intra_club_wins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tournament_name TEXT NOT NULL CHECK (char_length(tournament_name) BETWEEN 2 AND 120),
  opponent_name TEXT NOT NULL CHECK (char_length(opponent_name) BETWEEN 2 AND 80),
  proof_url TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_by UUID REFERENCES auth.users(id),
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS verification_status TEXT NOT NULL DEFAULT 'unverified'
  CHECK (verification_status IN ('unverified','pending','verified','rejected'));

ALTER TABLE public.club_announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.intra_club_wins ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Announcements visible to all" ON public.club_announcements;
CREATE POLICY "Announcements visible to all" ON public.club_announcements
FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Admins manage announcements" ON public.club_announcements;
CREATE POLICY "Admins manage announcements" ON public.club_announcements
FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "Players view own intra club wins" ON public.intra_club_wins;
CREATE POLICY "Players view own intra club wins" ON public.intra_club_wins
FOR SELECT TO authenticated USING (player_id = auth.uid() OR public.is_admin());
DROP POLICY IF EXISTS "Approved players submit own wins" ON public.intra_club_wins;
CREATE POLICY "Approved players submit own wins" ON public.intra_club_wins
FOR INSERT TO authenticated WITH CHECK (
  player_id = auth.uid() AND EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.approval_status = 'approved'
  )
);
DROP POLICY IF EXISTS "Admins review intra club wins" ON public.intra_club_wins;
CREATE POLICY "Admins review intra club wins" ON public.intra_club_wins
FOR UPDATE TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

GRANT SELECT ON public.club_announcements TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.club_announcements TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.intra_club_wins TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.club_announcements_id_seq TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.intra_club_wins_id_seq TO authenticated;

-- Secure admin-only squad and verification controls.
CREATE OR REPLACE FUNCTION public.manage_player_squad(target_id UUID, new_squad TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Admin access required'; END IF;
  IF new_squad NOT IN ('MAIN','ACADEMY','YOUTH','LEGEND') THEN RAISE EXCEPTION 'Invalid squad'; END IF;
  UPDATE public.profiles SET squad = new_squad WHERE id = target_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player not found'; END IF;
END; $$;

CREATE OR REPLACE FUNCTION public.set_player_verification(target_id UUID, new_status TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Admin access required'; END IF;
  IF new_status NOT IN ('verified','rejected','unverified') THEN RAISE EXCEPTION 'Invalid verification status'; END IF;
  UPDATE public.profiles SET verification_status = new_status WHERE id = target_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player not found'; END IF;
END; $$;

CREATE OR REPLACE FUNCTION public.request_player_verification()
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  UPDATE public.profiles SET verification_status = 'pending'
  WHERE id = auth.uid() AND approval_status = 'approved';
  IF NOT FOUND THEN RAISE EXCEPTION 'Approved player account required'; END IF;
END; $$;

GRANT EXECUTE ON FUNCTION public.manage_player_squad(UUID,TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.set_player_verification(UUID,TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.request_player_verification() TO authenticated;

